import { existsSync, readFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const mobileRoot = resolve(__dirname, '..');
const repoRoot = resolve(mobileRoot, '..');
const source = resolve(repoRoot, 'apps/web/public/openapi.json');
const target = resolve(mobileRoot, 'src/api/openapi.json');
const generatedTypes = resolve(mobileRoot, 'src/api/openapi.generated.ts');

function fail(message) {
  console.error(`OpenAPI sync check failed: ${message}`);
  process.exit(1);
}

function parseJson(label, value) {
  try {
    return JSON.parse(value);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    fail(`${label} is not valid JSON: ${message}`);
  }
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function readGeneratedPathBlock(generatedSource, apiPath) {
  const pathPattern = new RegExp(`^\\s+${escapeRegExp(JSON.stringify(apiPath))}:\\s*\\{`, 'm');
  const match = pathPattern.exec(generatedSource);
  if (!match) return null;

  const blockStart = match.index + match[0].length;
  const rest = generatedSource.slice(blockStart);
  const nextPath = /^ {4}"\/api\//m.exec(rest);
  return nextPath ? rest.slice(0, nextPath.index) : rest;
}

function assertGeneratedTypesCoverSpec(spec, generatedSource) {
  if (!generatedSource.includes('auto-generated by openapi-typescript')) {
    fail(`${relative(repoRoot, generatedTypes)} must be generated by openapi-typescript`);
  }

  const paths = Object.keys(spec.paths ?? {});
  const generatedPathBlocks = new Map(
    paths.map((apiPath) => [apiPath, readGeneratedPathBlock(generatedSource, apiPath)]),
  );
  const missingPaths = paths.filter((apiPath) => !generatedPathBlocks.get(apiPath));

  if (missingPaths.length) {
    fail(
      `${relative(repoRoot, generatedTypes)} is missing OpenAPI path types: ${missingPaths
        .slice(0, 10)
        .join(', ')}`,
    );
  }

  const httpMethods = new Set([
    'delete',
    'get',
    'head',
    'options',
    'patch',
    'post',
    'put',
    'trace',
  ]);
  const missingMethods = [];

  for (const [apiPath, pathSpec] of Object.entries(spec.paths ?? {})) {
    const pathBlock = generatedPathBlocks.get(apiPath);
    if (!pathBlock) continue;

    for (const method of Object.keys(pathSpec ?? {}).filter((key) => httpMethods.has(key))) {
      const methodPattern = new RegExp(`^\\s+${method}:\\s*\\{`, 'm');
      if (!methodPattern.test(pathBlock)) {
        missingMethods.push(`${method.toUpperCase()} ${apiPath}`);
      }
    }
  }

  if (missingMethods.length) {
    fail(
      `${relative(repoRoot, generatedTypes)} is missing OpenAPI operation types: ${missingMethods
        .slice(0, 10)
        .join(', ')}`,
    );
  }

  const schemaBlockStart = generatedSource.indexOf('schemas: {');
  if (schemaBlockStart === -1) {
    fail(`${relative(repoRoot, generatedTypes)} is missing generated component schemas`);
  }

  const schemaBlock = generatedSource.slice(schemaBlockStart);
  const schemas = Object.keys(spec.components?.schemas ?? {});
  const missingSchemas = schemas.filter((schemaName) => {
    const schemaPattern = new RegExp(`^\\s+${escapeRegExp(schemaName)}:\\s*`, 'm');
    return !schemaPattern.test(schemaBlock);
  });

  if (missingSchemas.length) {
    fail(
      `${relative(repoRoot, generatedTypes)} is missing OpenAPI schema types: ${missingSchemas
        .slice(0, 10)
        .join(', ')}`,
    );
  }
}

if (!existsSync(source)) {
  fail(`missing web OpenAPI source at ${relative(repoRoot, source)}`);
}

if (!existsSync(target)) {
  fail(`missing mobile OpenAPI copy at ${relative(repoRoot, target)}`);
}

if (!existsSync(generatedTypes)) {
  fail(`missing generated mobile OpenAPI types at ${relative(repoRoot, generatedTypes)}`);
}

const sourceSpec = readFileSync(source, 'utf8');
const targetSpec = readFileSync(target, 'utf8');

if (sourceSpec !== targetSpec) {
  fail(
    `${relative(repoRoot, target)} is out of sync with ${relative(
      repoRoot,
      source,
    )}. Run: pnpm --filter @tasknebula/mobile openapi:sync`,
  );
}

assertGeneratedTypesCoverSpec(
  parseJson(relative(repoRoot, target), targetSpec),
  readFileSync(generatedTypes, 'utf8'),
);

console.log(
  `OpenAPI sync check passed: ${relative(repoRoot, target)} matches ${relative(
    repoRoot,
    source,
  )}, and generated types cover the documented paths, operations, and schemas.`,
);
